def lettering(text, scale, top, width=395):
    cells=sum(4 if c==' ' else 6 for c in text)-1
    left=(width-cells*scale)/2
    paths=[]
    for letter in text:
        if letter==' ':
            left+=4*scale
            continue
        for y,row in enumerate(GRIDS[letter]):
            for x,pixel in enumerate(row):
                if pixel=='1':
                    paths.append(f'M{left+x*scale:g} {top+y*scale:g}h{scale}v{scale}h{-scale}z')
        left+=6*scale
    return ''.join(paths)

